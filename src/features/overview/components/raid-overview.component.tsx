export function Overview() {
    const [filterValue, setFilterValue] = React.useState('');
    const [visibleColumns, setVisibleColumns] = React.useState<Selection>(new Set(INITIAL_VISIBLE_COLUMNS));
    const [statusFilter, setStatusFilter] = React.useState<Selection>(new Set(['all']));
    const [sortDescriptor, setSortDescriptor] = React.useState<SortDescriptor>({
        column: 'name',
        direction: 'ascending',
    });
    const [selectedDataSource, setSelectedDataSource] = React.useState<PlayerRaidOverview[]>(raidOverviewData.overall);

    const hasSearchFilter = Boolean(filterValue);

    const headerColumns = React.useMemo(() => {
        if (visibleColumns === 'all') return columns;

        return columns.filter((column) => Array.from(visibleColumns).includes(column.uid));
    }, [visibleColumns]);

    const filteredItems = React.useMemo(() => {
        if (Array.from(statusFilter).at(0) !== 'all') {
            const cycleNumber: number = Number(Array.from(statusFilter));
            console.log('cycle number is', cycleNumber);
            const selectedRoundData = raidOverviewData.cycles.at(cycleNumber - 1);
            if (selectedRoundData != null && selectedRoundData.playersData != null) {
                setSelectedDataSource(selectedRoundData.playersData);
                console.log('setting data to cycle');
            }
        } else {
            console.log('setting data to overall');
            setSelectedDataSource(raidOverviewData.overall);
        }

        let filteredUsers = [...selectedDataSource];

        if (hasSearchFilter) {
            filteredUsers = filteredUsers.filter((user) => user.name.toLowerCase().includes(filterValue.toLowerCase()));
        }
        // if (statusFilter !== 'all' && Array.from(statusFilter).length !== statusOptions.length) {
        //     filteredUsers = filteredUsers.filter((user) => Array.from(statusFilter).includes(user.status));
        // }

        return filteredUsers;
    }, [filterValue, statusFilter]);

    const items = React.useMemo(() => {
        return filteredItems;
    }, [filteredItems]);

    const sortedItems = React.useMemo(() => {
        return [...items].sort((a: PlayerRaidOverview, b: PlayerRaidOverview) => {
            const first = a[sortDescriptor.column as keyof PlayerRaidOverview] as number;
            const second = b[sortDescriptor.column as keyof PlayerRaidOverview] as number;
            const cmp = first < second ? -1 : first > second ? 1 : 0;

            return sortDescriptor.direction === 'descending' ? -cmp : cmp;
        });
    }, [sortDescriptor, items]);

    const renderCell = React.useCallback((player: PlayerRaidOverview, columnKey: React.Key) => {
        const cellValue = player[columnKey as keyof PlayerRaidOverview];

        switch (columnKey) {
            case 'average_damage':
            case 'offstrat_damage':
                return (
                    <div className="items-cente flex flex-row justify-start">
                        <p className="text-bold text-small">{formatter().format(Number(cellValue))}</p>
                    </div>
                );

            // case 'actions':
            //     return (
            //         <div className="relative flex justify-end items-center gap-2">
            //             <Dropdown>
            //                 <DropdownTrigger>
            //                     <Button isIconOnly size="sm" variant="light">
            //                         <VerticalDotsIcon className="text-default-300" />
            //                     </Button>
            //                 </DropdownTrigger>
            //                 <DropdownMenu>
            //                     <DropdownItem>View</DropdownItem>
            //                     <DropdownItem>Edit</DropdownItem>
            //                     <DropdownItem>Delete</DropdownItem>
            //                 </DropdownMenu>
            //             </Dropdown>
            //         </div>
            //     );
            default:
                return <span className="flex items-center justify-start">{cellValue}</span>;
        }
    }, []);

    const onSearchChange = React.useCallback((value?: string) => {
        if (value) {
            setFilterValue(value);
        } else {
            setFilterValue('');
        }
    }, []);

    const onClear = React.useCallback(() => {
        setFilterValue('');
    }, []);

    const topContent = React.useMemo(() => {
        return (
            <div className="flex flex-col gap-4">
                <div className="flex items-center justify-between gap-3">
                    <Input
                        isClearable
                        label="Search"
                        className="w-full sm:max-w-[44%]"
                        radius="lg"
                        classNames={{
                            label: 'text-black/50 dark:text-white/90',
                            input: [
                                'bg-transparent',
                                'text-black/90 dark:text-white/90',
                                'placeholder:text-default-700/50 dark:placeholder:text-white/60',
                            ],
                            innerWrapper: 'bg-transparent',
                            inputWrapper: [
                                'bg-default-200/50',
                                'dark:bg-default/60',
                                'backdrop-blur-xl',
                                'backdrop-saturate-200',
                                'hover:bg-default-200/70',
                                'dark:hover:bg-default/70',
                                'group-data-[focused=true]:bg-default-200/50',
                                'dark:group-data-[focused=true]:bg-default/60',
                                '!cursor-text',
                            ],
                        }}
                        placeholder="Type to search..."
                        startContent={
                            <SearchIcon className="pointer-events-none mb-0.5 flex-shrink-0 text-black/50 text-slate-400 dark:text-white/90" />
                        }
                        value={filterValue}
                        onClear={() => onClear()}
                        onValueChange={onSearchChange}
                    />
                    <div className="flex gap-3">
                        <Dropdown>
                            <DropdownTrigger className="hidden sm:flex">
                                <Button endContent={<ChevronDownIcon className="text-small" />} variant="flat">
                                    Rounds
                                </Button>
                            </DropdownTrigger>
                            <DropdownMenu
                                disallowEmptySelection
                                aria-label="Table Columns"
                                closeOnSelect={true}
                                selectedKeys={statusFilter}
                                selectionMode="single"
                                onSelectionChange={setStatusFilter}
                            >
                                {cycleOptions.map((cycle) => (
                                    <DropdownItem key={cycle.uid} className="capitalize">
                                        {cycle.name}
                                    </DropdownItem>
                                ))}
                            </DropdownMenu>
                        </Dropdown>
                        <Dropdown>
                            <DropdownTrigger className="hidden sm:flex">
                                <Button endContent={<ChevronDownIcon className="text-small" />} variant="flat">
                                    Columns
                                </Button>
                            </DropdownTrigger>
                            <DropdownMenu
                                disallowEmptySelection
                                aria-label="Table Columns"
                                closeOnSelect={false}
                                selectedKeys={visibleColumns}
                                selectionMode="multiple"
                                onSelectionChange={setVisibleColumns}
                            >
                                {columns.map((column) => (
                                    <DropdownItem key={column.uid} className="capitalize">
                                        {capitalize(column.name)}
                                    </DropdownItem>
                                ))}
                            </DropdownMenu>
                        </Dropdown>
                    </div>
                </div>
            </div>
        );
    }, [filterValue, statusFilter, visibleColumns, onSearchChange, hasSearchFilter]);

    return (
        <Table
            aria-label="Example table with custom cells, pagination and sorting"
            isHeaderSticky={true}
            sortDescriptor={sortDescriptor}
            topContent={topContent}
            topContentPlacement="outside"
            onSortChange={setSortDescriptor}
            classNames={{
                wrapper: 'max-h-[764px]',
            }}
        >
            <TableHeader columns={headerColumns}>
                {(column) => (
                    <TableColumn key={column.uid} allowsSorting={column.sortable}>
                        {column.name}
                    </TableColumn>
                )}
            </TableHeader>
            <TableBody emptyContent={'No players found'} items={sortedItems}>
                {(item) => <TableRow key={item.id}>{(columnKey) => <TableCell>{renderCell(item, columnKey)}</TableCell>}</TableRow>}
            </TableBody>
        </Table>
    );
}
